function translateText(value, messages) {
  const trimmed = value.trim()
  const translation = messages[trimmed]
  if (translation) return value.replace(trimmed, translation)

  return Object.entries(messages)
    .sort(([left], [right]) => right.length - left.length)
    .reduce((translatedValue, [source, replacement]) => translatedValue.replaceAll(source, replacement), value)
}

export function localizePortfolioTemplate(document, locale) {
  if (!document) return

  document.documentElement.lang = locale
  const messages = templateMessages[locale] || templateMessages.es
  const textNodes = document.evaluate(
    './/text()[normalize-space() and not(ancestor::script or ancestor::style)]',
    document.body,
    null,
    XPathResult.ORDERED_NODE_SNAPSHOT_TYPE,
    null,
  )

  for (let index = 0; index < textNodes.snapshotLength; index += 1) {
    const node = textNodes.snapshotItem(index)
    node.nodeValue = translateText(node.nodeValue, messages)
  }

  const interactiveLocalization = document.createElement('script')
  interactiveLocalization.textContent = `(() => {
    const messages = ${JSON.stringify(messages)};
    const translate = (value) => {
      const trimmed = value.trim();
      if (messages[trimmed]) return value.replace(trimmed, messages[trimmed]);
      return Object.entries(messages)
        .sort(([left], [right]) => right.length - left.length)
        .reduce((translatedValue, [source, replacement]) => translatedValue.split(source).join(replacement), value);
    };
    const translateElement = (element) => {
      const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
      const nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      nodes.forEach((node) => { node.nodeValue = translate(node.nodeValue); });
    };
    new MutationObserver((records) => {
      records.forEach((record) => record.addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
        if (node.nodeType === Node.TEXT_NODE) node.nodeValue = translate(node.nodeValue);
      }));
    }).observe(document.body, { childList: true, subtree: true });

    document.addEventListener('click', (event) => {
      const link = event.target.closest('a[href^="#"]');
      const href = link?.getAttribute('href');
      if (!href || href === '#') return;
      const target = document.getElementById(decodeURIComponent(href.slice(1)));
      if (!target) return;
      event.preventDefault();
      target.scrollIntoView({ behavior: 'smooth', block: 'start' });
      if (location.protocol !== 'about:') history.replaceState(null, '', href);
    });
  })();`
  document.body.append(interactiveLocalization)
}